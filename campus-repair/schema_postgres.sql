-- โครงตารางสำหรับ PostgreSQL บน Neon สร้างเฉพาะตารางที่ยังไม่มี

-- บัญชีผู้ใช้และสิทธิ์ เก็บรหัสผ่านเป็นแฮช
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin')),
 created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS'))
);
-- รายการแจ้งซ่อมและสถานะล่าสุด
CREATE TABLE IF NOT EXISTS repairs (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id),
 equipment TEXT NOT NULL,
 room TEXT NOT NULL,
 description TEXT NOT NULL,
 contact TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','working','done','unrepairable')),
 created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS')),
 updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS'))
);
-- ประวัติการเปลี่ยนสถานะ พร้อมผู้ดำเนินการและบันทึก
CREATE TABLE IF NOT EXISTS repair_history (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repair_id INTEGER NOT NULL REFERENCES repairs(id),
 actor_id INTEGER NOT NULL REFERENCES users(id),
 status TEXT NOT NULL CHECK(status IN ('pending','working','done','unrepairable')),
 note TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS'))
);
-- เพิ่มดัชนีช่วยให้ค้นหาข้อมูลได้เร็วขึ้น
CREATE INDEX IF NOT EXISTS idx_repairs_user ON repairs(user_id);
-- เพิ่มดัชนีช่วยให้ค้นหาข้อมูลได้เร็วขึ้น
CREATE INDEX IF NOT EXISTS idx_repairs_status ON repairs(status);
-- เพิ่มดัชนีช่วยให้ค้นหาข้อมูลได้เร็วขึ้น
CREATE INDEX IF NOT EXISTS idx_history_repair ON repair_history(repair_id);
-- ชื่อผู้แจ้ง รหัสนักศึกษา และภาพหลักฐานของแต่ละรายการ
CREATE TABLE IF NOT EXISTS repair_evidence (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repair_id INTEGER NOT NULL UNIQUE REFERENCES repairs(id),
 reporter_name TEXT NOT NULL,
 student_id TEXT NOT NULL,
 photo BYTEA NOT NULL CHECK(octet_length(photo) <= 512000)
);

-- ข้อมูลสมาชิกเพิ่มเติม แยกตารางเพื่อให้บัญชีเดิมยังใช้ได้
CREATE TABLE IF NOT EXISTS user_profiles (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
 email TEXT NOT NULL,
 title TEXT NOT NULL,
 student_id TEXT NOT NULL DEFAULT '',
 faculty TEXT NOT NULL DEFAULT '',
 major TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_profile_email ON user_profiles(lower(email));
-- เก็บอีเมลรอส่ง หากส่งไม่ได้สามารถลองส่งใหม่ผ่าน CLI
CREATE TABLE IF NOT EXISTS email_outbox (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient TEXT NOT NULL,
 subject TEXT NOT NULL,
 body TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sending','sent')),
 attempts INTEGER NOT NULL DEFAULT 0
);
